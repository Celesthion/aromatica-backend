package com.aromatica.modules.inventory.doc.model;

/** Тип складского документа. Знак движения определяется правилами проведения. */
public enum DocType {
    SUPPLY,     // приёмка (+)
    SALE,       // продажа (−)
    WRITE_OFF,  // списание (−)
    SURPLUS,    // оприходование (+)
    INVENTORY,  // инвентаризация (строки = факт, разницу система считает сама)
    MOVE,       // перемещение между складами
    CONVERT,    // вскрытие: строка 1 = источник (−, шт), строка 2 = приёмник (+, мл)
    RETURN,     // возврат от покупателя (+товар по себестоимости чека, деньги −)
    RETURN_SUPPLY, // возврат поставщику (−товар по средней, деньги +)
    ASSEMBLY,   // сборка: составляющие (−) → вещь с составом (+), см. docs/KITS-SHELF.md
    DISASSEMBLY // разборка: вещь (−) → составляющие (+) по долям себестоимости
}
